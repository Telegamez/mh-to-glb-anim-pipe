"""Import the Avaturn source GLB and build a Mixamo/Avaturn -> MetaHuman retargeter. NEW assets only, all
under /Game/LibFix/Avaturn. Existing assets (IK_AutoGeneratedTarget, SKM_Tele1_BodyMesh) are referenced, not edited.

Env: MH_AV_GLB (source glb), MH_AV_STAGE = import | rig | retarget | all

    # 1. Blender: Avaturn library armature + chosen actions + a skinned Avaturn mesh -> one GLB
    blender -b --factory-startup -P make_avaturn_src.py -- <avaturn animations.glb> <Avaturn character.glb> <AvaturnSrc.glb>
    # 2. headless UE: import, IK rig, retargeter, batch retarget into /Game/LibFix/Avaturn/Retargeted
    $env:MH_AV_GLB='<AvaturnSrc.glb>'; UnrealEditor-Cmd <project> -run=pythonscript -script=build_avaturn_retarget.py -unattended -nosplash -nullrhi

The Avaturn talk-show library was deleted from telegamez in 07b9dbb6b; recover it with
`git show 07b9dbb6b^:packages/web-next/public/models/agent-tele/animations.glb`. The source mesh is
any Avaturn character GLB with the same Mixamo-style joint names (S:/Avatars/models/NY-Man/NY.glb was used).
"""
import os
import unreal  # type: ignore

DEST = "/Game/LibFix/Avaturn"
OUTD = DEST + "/Retargeted"
GLB = os.environ.get("MH_AV_GLB", "")
STAGE = os.environ.get("MH_AV_STAGE", "all")
TGT_RIG = "/Game/Animations/IK_AutoGeneratedTarget"
TGT_MESH = "/Game/MetaHumans/Tele/Body/SKM_Tele1_BodyMesh"
tools = unreal.AssetToolsHelpers.get_asset_tools()
EAL = unreal.EditorAssetLibrary
reg = unreal.AssetRegistryHelpers.get_asset_registry()


def log(m):
    print(f"[avrtg] {m}", flush=True); unreal.log(f"[avrtg] {m}")


def assets_in(path, cls=None):
    out = []
    for ad in reg.get_assets_by_path(path, True):
        if cls is None or str(ad.asset_class_path.asset_name) == cls:
            out.append(ad)
    return out


for d in (DEST, OUTD):
    if not EAL.does_directory_exist(d):
        EAL.make_directory(d)

if STAGE in ("import", "all"):
    for d in (DEST + "/Src", OUTD):   # our own LibFix assets from a previous attempt
        if EAL.does_directory_exist(d):
            EAL.delete_directory(d)
    EAL.make_directory(OUTD)
    task = unreal.AssetImportTask()
    task.filename = GLB
    task.destination_path = DEST + "/Src"
    task.automated = True
    task.save = True
    task.replace_existing = True
    tools.import_asset_tasks([task])
    log(f"imported: {list(task.imported_object_paths)}")
    for ad in assets_in(DEST + "/Src"):
        log(f"  {ad.asset_class_path.asset_name} {ad.package_name}")

meshes = assets_in(DEST + "/Src", "SkeletalMesh")
if not meshes:
    raise SystemExit("no SkeletalMesh imported")
src_mesh = meshes[0].get_asset()
log(f"source mesh {src_mesh.get_path_name()} skeleton {src_mesh.get_editor_property('skeleton').get_path_name()}")

rig_path = DEST + "/IK_Avaturn"
if STAGE in ("rig", "all"):
    if EAL.does_asset_exist(rig_path):
        EAL.delete_asset(rig_path)
    rig = tools.create_asset("IK_Avaturn", DEST, unreal.IKRigDefinition, unreal.IKRigDefinitionFactory())
    c = unreal.IKRigController.get_controller(rig)
    c.set_skeletal_mesh(src_mesh)
    log("IKRigController methods: " + ", ".join(m for m in dir(c) if not m.startswith("_")))
    ok = c.apply_auto_generated_retarget_definition()
    log(f"auto retarget definition: {ok}; root={c.get_retarget_root()}; chains={[str(ch.chain_name) for ch in c.get_retarget_chains()]}")
    EAL.save_asset(rig_path)
rig = unreal.load_asset(rig_path)

rtg_path = DEST + "/RTG_Avaturn_to_MetaHuman"
if STAGE in ("retarget", "all"):
    if EAL.does_asset_exist(rtg_path):
        EAL.delete_asset(rtg_path)
    rtg = tools.create_asset("RTG_Avaturn_to_MetaHuman", DEST, unreal.IKRetargeter, unreal.IKRetargetFactory())
    rc = unreal.IKRetargeterController.get_controller(rtg)
    log("IKRetargeterController methods: " + ", ".join(m for m in dir(rc) if not m.startswith("_")))
    S, T = unreal.RetargetSourceOrTarget.SOURCE, unreal.RetargetSourceOrTarget.TARGET
    rc.set_ik_rig(S, rig)
    rc.set_ik_rig(T, unreal.load_asset(TGT_RIG))
    rc.set_preview_mesh(S, src_mesh)
    rc.set_preview_mesh(T, unreal.load_asset(TGT_MESH))
    for name, call in (("add_default_ops", lambda: rc.add_default_ops()),
                       ("assign_ik_rig_to_all_ops", lambda: rc.assign_ik_rig_to_all_ops(S, rig))):
        if hasattr(rc, name):
            try:
                call(); log(f"{name}: ok")
            except Exception as e:  # noqa
                log(f"{name}: {e}")
    # The glTF import puts its Y-up->Z-up correction on the proxy root's ANIMATION track (90 deg roll)
    # but not on its reference pose; the Root Motion op copies that onto the MetaHuman root and tips the
    # whole body over. MetaHuman companion clips keep an identity root, so the op is switched off.
    for i in range(rc.get_num_retarget_ops()):
        if str(rc.get_op_name(i)) == "Root Motion":
            rc.set_retarget_op_enabled(i, False)
            log(f"op {i} Root Motion disabled: {not rc.get_retarget_op_enabled(i)}")
    try:
        rc.auto_map_chains(unreal.AutoMapChainType.FUZZY, True)
        log("auto_map_chains fuzzy: ok")
    except Exception as e:  # noqa
        log(f"auto_map_chains: {e}")
    for side, lab in ((S, "source"), (T, "target")):
        try:
            rc.auto_align_all_bones(side); log(f"auto_align_all_bones {lab}: ok")
        except Exception as e:  # noqa
            log(f"auto_align_all_bones {lab}: {e}")
    try:
        log(f"chain map: {[(str(m.target_chain), str(m.source_chain)) for m in rc.get_chain_mappings()]}" if hasattr(rc, 'get_chain_mappings') else "no get_chain_mappings")
    except Exception as e:  # noqa
        log(f"chain map read: {e}")
    EAL.save_asset(rtg_path)
    rtg = unreal.load_asset(rtg_path)
    anims = assets_in(DEST + "/Src", "AnimSequence")
    log(f"retargeting {[str(a.asset_name) for a in anims]}")
    out = unreal.IKRetargetBatchOperation.duplicate_and_retarget(anims, src_mesh, unreal.load_asset(TGT_MESH), rtg,
                                                                 "", "", "LF_AV_", "", OUTD)
    for ad in out:
        a = unreal.load_asset(str(ad.package_name))
        sk = a.get_editor_property("skeleton") if isinstance(a, unreal.AnimSequence) else None
        log(f"  out {ad.package_name} {a.get_class().get_name()} len={a.get_editor_property('sequence_length') if sk else '-'} skel={sk.get_path_name() if sk else None}")
        EAL.save_asset(str(ad.package_name), only_if_is_dirty=False)
log("done")
